import type { Post, PostCategory } from "@/domain/post";

const avatar = "/brand/default-avatar.svg";

function image(
  postId: string,
  url: string,
  alt: string,
  width: number,
  height: number,
) {
  return {
    id: `${postId}-media-1`,
    type: "image" as const,
    url,
    alt,
    width,
    height,
    position: 0,
  };
}

function post(
  id: string,
  title: string,
  creatorName: string,
  category: PostCategory,
  description: string,
  url: string,
  width: number,
  height: number,
  styles: string[],
  colors: string[],
  industries: string[],
): Post {
  const creatorId = creatorName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

  return {
    id,
    slug: title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, ""),
    title,
    creator: {
      id: `seed-${creatorId}`,
      name: creatorName,
      avatarUrl: avatar,
    },
    description,
    category,
    styles,
    colors,
    industries,
    sourceUrl: url.startsWith("http") ? url : "https://www.behance.net/",
    publishedAt: `2026-07-${String(31 - Number(id)).padStart(2, "0")}T10:00:00.000Z`,
    media: [image(id, url, title, width, height)],
  };
}

